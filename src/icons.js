export function icon(name, size = 18, cls = '') {
  const def = P[name];
  if (!def) return '';
  const filled = typeof def === 'object';
  const body = filled ? def.d : def;
  const attrs = filled
    ? 'fill="currentColor" stroke="none"'
    : 'fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"';
  return `<svg class="i ${cls}" width="${size}" height="${size}" viewBox="0 0 24 24" ${attrs} aria-hidden="true">${body}</svg>`;
}

// Replaces <i data-icon="name" data-size="16"></i> placeholders.
export function hydrateIcons(root = document) {
  root.querySelectorAll('i[data-icon]').forEach((el) => {
    el.outerHTML = icon(el.dataset.icon, Number(el.dataset.size) || 18, el.className);
  });
}
